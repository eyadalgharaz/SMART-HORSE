/**
 * Realistic sample training data for the same stable the Horses module uses.
 *
 * Every session and program points at a real horse id from `buildHorseMocks()`
 * and takes the horse's name from it, so Training can never disagree with
 * Horse Management about who a horse is. A handful of horses deliberately have
 * no sessions at all — that is what makes "no training history for this horse"
 * reviewable without editing code.
 *
 * Every date is an offset in days from `now`, so "this week", "upcoming" and
 * "overdue" stay true whenever the page is opened. The set is deliberately
 * uneven: every training type, every session status, five trainers, sessions
 * with and without tracked performance metrics, sessions tied to a program and
 * sessions that are not. That is what makes search, filters, badges, the
 * timeline and the progress chart reviewable.
 *
 * This file is fake data only — nothing here implies a backend exists.
 */

function horseName(id: string): string {
  return buildHorseMocks().find((horse) => horse.id === id)?.name ?? id;
}

/** Local calendar day `offsetDays` from `now`, at the given clock time. */
function at(now: Date, offsetDays: number, hour = 9, minute = 0): string {
  return new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() + offsetDays,
    hour,
    minute,
  ).toISOString();
}

