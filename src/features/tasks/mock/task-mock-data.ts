/**
 * Realistic sample task data for the same stable the Horses, Medical and
 * Training modules use.
 *
 * Every horse-linked task points at a real horse id from `buildHorseMocks()`
 * and takes the horse's name from it, so Tasks can never disagree with Horse
 * Management about who a horse is. Several tasks are deliberately
 * farm-wide — administrative or stable work with no horse at all — since not
 * everything a stable does is about one animal.
 *
 * Every date is an offset in days from `now`, so "due today", "overdue" and
 * "this week" stay true whenever the page is opened. The set is deliberately
 * uneven: every category, every priority, every status, every recurrence
 * option, tasks with and without a due date, and tasks with and without a
 * horse or an assignee. That is what makes search, filters, tabs, the
 * summary and the completion flow reviewable.
 *
 * This file is fake data only — nothing here implies a backend exists.
 */

function horseName(id: string | null): string | null {
  if (id === null) return null;
  return buildHorseMocks().find((horse) => horse.id === id)?.name ?? id;
}

/** Local calendar day `offsetDays` from `now`, at the given clock time. */
function at(now: Date, offsetDays: number, hour = 9, minute = 0): string {
  return new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate() + offsetDays,
    hour,
    minute,
  ).toISOString();
}

