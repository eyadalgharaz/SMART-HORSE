export function buildTaskMocks(now: Date = new Date()): Task[] {
  return TASK_SPECS.map((spec) => {
    const dueAt =
      spec.offsetDays === null ? null : at(now, spec.offsetDays, spec.hour, spec.minute);
    const completedAt =
      spec.status === 'completed'
        ? at(now, (spec.offsetDays ?? 0) + (spec.completedOffset ?? 0), spec.hour, spec.minute)
        : null;

    return {
      id: spec.id,
      title: spec.title,
      description: spec.description,
      category: spec.category,
      horseId: spec.horseId,
      horseName: horseName(spec.horseId),
      assigneeId: spec.assigneeId,
      assigneeName: assigneeName(spec.assigneeId),
      dueAt,
      priority: spec.priority,
      status: spec.status,
      recurrence: { frequency: spec.recurrence },
      notes: spec.notes,
      createdAt: at(now, (spec.offsetDays ?? 0) - spec.createdOffset, 9, 0),
      completedAt,
    };
  });
}
